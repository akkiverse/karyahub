import { icon } from '../ui/icons.js';
import { escapeHtml, rupees, rupeesExact, prettyDate, prettyPhone } from '../format.js';
import { docTitle, lineIsValid } from '../domain/documents.js';

export const WATERMARK = 'DEMO, not a valid tax invoice';

export function documentView({ state, params, ui }) {
  const d = state.documents.find((x) => x.id === params.id);
  if (!d) return `<section class="page"><h1 id="page-title" tabindex="-1">Document not found</h1><p>It may no longer be on this device.</p><a class="btn btn-ghost" href="#/jobs">Back to Jobs</a></section>`;
  const s = state.settings;
  return `<section class="page doc-page">
    <div class="doc-toolbar no-print">
      <a class="back" href="#/jobs/${d.job_id}">${icon('arrowLeft', { size: 18 })} Job ${d.job_id}</a>
      <button type="button" class="btn btn-primary" data-action="download" data-testid="download">${icon('download', { size: 18 })} Download</button>
    </div>
    ${ui.toast && ui.toast.where === 'doc' ? `<p class="notice no-print ${ui.toast.error ? 'notice-error' : ''}" role="status">${escapeHtml(ui.toast.text)}</p>` : ''}
    <article class="doc" data-testid="document" aria-labelledby="page-title">
      ${s.is_demo ? `<div class="watermark" data-testid="watermark" aria-label="${WATERMARK}">${WATERMARK}</div>` : ''}
      <header class="doc-head">
        <div>
          <p class="doc-biz" data-testid="doc-business">${escapeHtml(s.business_name)}${s.is_demo ? ' <span class="demo-tag">demo</span>' : ''}</p>
          <p class="muted">${escapeHtml(s.address)}</p>
          <p class="muted">GSTIN <span data-testid="doc-gstin">${escapeHtml(s.gstin)}</span>${s.is_demo ? ' (dummy)' : ''}</p>
        </div>
        <div class="doc-meta">
          <h1 id="page-title" tabindex="-1">${docTitle(d.type)}</h1>
          <p><strong>${d.id}</strong></p>
          <p class="muted">${prettyDate(d.date)}</p>
        </div>
      </header>
      <section class="doc-to">
        <p class="label">Bill to</p>
        <p data-testid="doc-customer"><strong>${escapeHtml(d.customer.name)}</strong></p>
        <p class="muted">${escapeHtml(d.customer.area || '')}${d.customer.phone ? ` · ${prettyPhone(d.customer.phone)}` : ''}</p>
      </section>
      <table class="doc-table" data-testid="doc-lines">
        <thead><tr><th scope="col">Item</th><th scope="col" class="num">Qty</th><th scope="col" class="num">Rate</th><th scope="col" class="num">Amount</th></tr></thead>
        <tbody>${d.lines
          .map((l, i) => {
            const ok = lineIsValid(l);
            return `<tr class="${ok ? '' : 'bad-line'}"><td>${escapeHtml(l.description)}${ok ? '' : `<small class="field-error" role="alert">Check quantity and rate</small>`}</td>
            <td class="num"><input class="cell-input no-print-input" aria-label="Quantity for ${escapeHtml(l.description)}" data-action="edit-line" data-doc="${d.id}" data-index="${i}" data-key="qty" type="number" min="1" step="1" value="${escapeHtml(l.qty)}"><span class="print-only">${escapeHtml(l.qty)}</span></td>
            <td class="num"><input class="cell-input no-print-input" aria-label="Rate for ${escapeHtml(l.description)}" data-action="edit-line" data-doc="${d.id}" data-index="${i}" data-key="rate" type="number" min="0" step="1" value="${escapeHtml(l.rate)}"><span class="print-only">${rupeesExact(l.rate)}</span></td>
            <td class="num">${ok ? rupeesExact(l.qty * l.rate) : '-'}</td></tr>`;
          })
          .join('')}</tbody>
      </table>
      <dl class="doc-totals" data-testid="doc-totals">
        <div><dt>Subtotal</dt><dd data-testid="subtotal">${rupeesExact(d.subtotal)}</dd></div>
        <div><dt>CGST 9%</dt><dd data-testid="cgst">${rupeesExact(d.cgst)}</dd></div>
        <div><dt>SGST 9%</dt><dd data-testid="sgst">${rupeesExact(d.sgst)}</dd></div>
        <div><dt>GST 18% in total</dt><dd>${rupeesExact(d.cgst + d.sgst)}</dd></div>
        ${d.roundOff ? `<div><dt>Round off</dt><dd>${rupeesExact(d.roundOff)}</dd></div>` : ''}
        <div class="grand"><dt>Total</dt><dd data-testid="total">${rupees(d.total)}</dd></div>
      </dl>
      <footer class="doc-foot muted">${d.type === 'quote' ? 'Quotation valid for 15 days.' : 'Thank you for your business.'}${s.is_demo ? ' Sample document generated by the KaryaHub demo. All details are dummy data.' : ''}</footer>
    </article>
  </section>`;
}
